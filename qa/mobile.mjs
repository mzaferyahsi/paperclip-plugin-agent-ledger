// Dev-only: phone-width checks (names and numbers visible together, tap to expand, filters, no sideways scroll, desktop unchanged).
import { chromium } from '/home/paperclip/node_modules/playwright/index.mjs';
const out = new URL('./shots/', import.meta.url).pathname;
const b = await chromium.launch({ headless: true, executablePath: '/home/paperclip/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome' });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, colorScheme: 'dark' });
const p = await ctx.newPage(); const errors = []; p.on('pageerror', (e) => errors.push(String(e)));
await p.goto('http://127.0.0.1:3101/QAT/agent-ledger'); await p.waitForSelector('.ou .mlist', { timeout: 20000 }); await p.waitForTimeout(1500);
const overflow = () => p.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth + 1 || document.querySelector('.ou').scrollWidth > document.querySelector('.ou').clientWidth + 1);
console.log('table present on phone:', await p.locator('.ou table').count(), '| list rows:', await p.locator('.mrow').count(), '| sideways overflow:', await overflow());
const first = p.locator('.mrow').nth(1);
const nb = await first.locator('.mname').boundingBox(), nu = await first.locator('.mnum b').boundingBox();
console.log('name box', JSON.stringify(nb), 'number box', JSON.stringify(nu), '| both inside 390px viewport:', nb.x + nb.width <= 390 && nu.x + nu.width <= 390);
await p.screenshot({ path: out + 'm-list.png' });
await first.locator('.mmain').tap(); await p.waitForTimeout(300);
console.log('detail open:', await p.locator('.mdet').count() > 0, '| flag meaning shown:', (await p.locator('.mdet').first().innerText()).includes('This agent:'));
await p.screenshot({ path: out + 'm-detail.png' });
const rowsBefore = await p.locator('.mrow').count();
await p.locator('.mchev:not(.e)').first().tap(); await p.waitForTimeout(300);
console.log('rows before/after collapsing first manager:', rowsBefore, await p.locator('.mrow').count());
await p.getByRole('button', { name: /Filters/ }).tap(); await p.waitForTimeout(300);
await p.screenshot({ path: out + 'm-filters.png' });
await p.getByLabel('Sort by').selectOption('tokens'); await p.waitForTimeout(300);
console.log('flat sort first row:', (await p.locator('.mrow .mname').first().innerText()), '| sideways overflow:', await overflow());
await p.getByLabel('Time range').selectOption('30d'); await p.waitForTimeout(800);
console.log('errors', errors);
const d = await b.newPage({ viewport: { width: 1300, height: 900 } });
await d.goto('http://127.0.0.1:3101/QAT/agent-ledger'); await d.waitForSelector('.ou table', { timeout: 20000 });
console.log('desktop: table', await d.locator('.ou table').count(), 'mobile list', await d.locator('.ou .mlist').count());
await b.close();
